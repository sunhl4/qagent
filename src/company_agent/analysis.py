"""Managed analysis templates: authorized summaries, unit audits and chart descriptors.

Survey source: docs/oss-survey/04-工程衔接建议.zh-CN.md 「P1: 结果回收、分析模板」.
Governance per template (`contracts/templates.json`):

- 输入来源 (``sources``): metric tables are operator-supplied snapshots taken
  from the listed tools; the adapter never fetches, dispatches or re-executes
  anything, so a template cannot cause platform side effects.
- schema 版本 (``metric_schema``): the input must carry the fixed metrics
  schema tag; anything else fails closed.
- 单位/完整性 (``domain``): domain-rule violations (unit/kind coupling,
  ranges, duplicate names, empty tables) are *flagged* — reported honestly —
  while structural violations (unknown template, malformed inputs, NaN) fail
  closed with an error, exactly as ``error_behavior`` in the contract demands.
- 权限范围: visibility per preset is governed by ``contracts/presets.json``;
  outputs never raise trust, never contain full circuit bodies, bitstrings or
  credential-shaped data, and charts are declarative descriptors generated by
  this adapter — never free text that could smuggle scripts, URLs or paths.
"""

from __future__ import annotations

import math
from collections.abc import Mapping
from typing import Any

from company_agent.catalog import load_templates
from company_agent.sanitize import validate_output_content


def _reasons_list(reasons: set[str]) -> list[str]:
    return sorted(reasons)[:8]


def _semantic_audit(
    items: list[Any],
) -> tuple[str, set[str], list[str], list[float], dict[str, list[tuple[str, float]]]]:
    """Shared semantic audit: (status, reasons, units, finite values, unit groups).

    Mirrors the metric rules of the provider result contract (count/probability
    unit coupling, range coupling) but reports them as flags instead of
    failures: a metrics table is an operator snapshot, not a platform dispatch.
    """

    reasons: set[str] = set()
    names: set[str] = set()
    units_present: list[str] = []
    values: list[float] = []
    groups: dict[str, list[tuple[str, float]]] = {}
    for item in items:
        name = item["name"]
        kind = item["kind"]
        value = item["value"]
        unit = item["unit"]
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
            raise ValueError("metrics table value must be a finite number")
        values.append(float(value))
        groups.setdefault(unit, []).append((name, float(value)))
        if kind in {"probability", "probabilities"}:
            if unit != "dimensionless":
                reasons.add("invalid_unit")
            elif not 0 <= value <= 1:
                reasons.add("range_violation")
        elif kind == "count":
            if unit != "count":
                reasons.add("invalid_unit")
            elif (
                (isinstance(value, float) and int(value) != value)
                or (isinstance(value, int) and isinstance(value, bool))
                or value < 0
            ):
                reasons.add("range_violation")
        elif kind == "uncertainty" and value < 0:
            reasons.add("range_violation")
        if kind not in {"probability", "probabilities", "count", "uncertainty"} and unit == "count":
            reasons.add("invalid_unit")
        if name in names:
            reasons.add("duplicate_name")
        names.add(name)
        if unit not in units_present:
            units_present.append(unit)
    status = "flagged" if reasons else "complete"
    return status, reasons, units_present, values, groups


def _charts(groups: dict[str, list[tuple[str, float]]], reasons: set[str]) -> list[dict[str, Any]]:
    charts: list[dict[str, Any]] = []
    for unit in sorted(groups):
        if len(charts) >= 8:
            reasons.add("chart_budget")
            break
        members = sorted(groups[unit], key=lambda row: (-row[1], row[0]))
        if len(members) > 16:
            reasons.add("chart_budget")
            members = members[:16]
        charts.append({
            "kind": "bar",
            "unit": unit[:64],
            "items": [{"name": name[:240], "value": value} for name, value in members],
        })
    if len(groups) > 8:
        reasons.add("chart_budget")
    return charts


def _metric_summary(arguments: Mapping[str, Any], template: Mapping[str, Any]) -> dict[str, Any]:
    metrics = arguments.get("metrics")
    if not isinstance(metrics, dict):
        raise ValueError("analysis template requires a metrics table")
    if metrics.get("schema_version") != template["metric_schema"]:
        raise ValueError("analysis metrics schema version mismatch")
    items = metrics.get("items")
    if not isinstance(items, list):
        raise ValueError("analysis metrics table is invalid")
    if not items:
        row = {
            "template": template["id"],
            "status": "flagged",
            "audit": {
                "complete": False, "items": 0,
                "reasons": _reasons_list({"empty"}), "units": [],
            },
            "charts": [],
        }
        return row
    status, reasons, units_present, values, groups = _semantic_audit(items)
    return {
        "template": template["id"],
        "status": status,
        "audit": {
            "complete": not reasons,
            "items": len(items),
            "reasons": _reasons_list(reasons),
            "units": units_present[:16],
            **({"min_value": min(values), "max_value": max(values)} if values else {}),
        },
        "charts": [] if reasons else _charts(groups, reasons),
    }


def _shots_audit(arguments: Mapping[str, Any], template: Mapping[str, Any]) -> dict[str, Any]:
    shots = arguments.get("shots")
    if not isinstance(shots, dict):
        raise ValueError("shots-audit template requires a shots delivery record")
    requested = shots.get("requested")
    actual = shots.get("actual")
    if (
        not isinstance(requested, int) or isinstance(requested, bool) or requested < 1
        or not isinstance(actual, int) or isinstance(actual, bool) or actual < 0
    ):
        raise ValueError("shots delivery record is invalid")
    reasons: set[str] = set()
    if actual > requested:
        reasons.add("overdelivery")
    elif actual < requested:
        reasons.add("underdelivery")
    return {
        "template": template["id"],
        "status": "flagged" if reasons else "complete",
        "audit": {
            "complete": not reasons,
            "items": 1,
            "reasons": _reasons_list(reasons),
            "units": ["count"],
        },
        "charts": [],
    }


def _quantile_charts(
    groups: dict[str, list[tuple[str, float]]],
) -> tuple[list[dict[str, Any]], bool]:
    """Declarative order-statistics charts: min/q25/median/q75/max per unit."""

    charts: list[dict[str, Any]] = []
    budget_exceeded = False
    for unit in sorted(groups):
        if len(charts) >= 8:
            budget_exceeded = True
            break
        ordered = sorted(value for _, value in groups[unit])
        marks = [("min", 0.0), ("q25", 0.25), ("median", 0.5), ("q75", 0.75), ("max", 1.0)]
        charts.append({
            "kind": "bar",
            "unit": unit[:64],
            "items": [
                {
                    "name": name,
                    "value": ordered[min(int(math.floor(fraction * (len(ordered) - 1))), len(ordered) - 1)],
                }
                for name, fraction in marks
            ],
        })
    if len(groups) > 8:
        budget_exceeded = True
    return charts, budget_exceeded


def _metric_quantiles(arguments: Mapping[str, Any], template: Mapping[str, Any]) -> dict[str, Any]:
    metrics = arguments.get("metrics")
    if not isinstance(metrics, dict):
        raise ValueError("analysis template requires a metrics table")
    if metrics.get("schema_version") != template["metric_schema"]:
        raise ValueError("analysis metrics schema version mismatch")
    items = metrics.get("items")
    if not isinstance(items, list):
        raise ValueError("analysis metrics table is invalid")
    if not items:
        return {
            "template": template["id"],
            "status": "flagged",
            "audit": {"complete": False, "items": 0, "reasons": _reasons_list({"empty"}), "units": []},
            "charts": [],
        }
    status, reasons, units_present, values, groups = _semantic_audit(items)
    charts: list[dict[str, Any]] = []
    if not reasons:
        charts, budget_exceeded = _quantile_charts(groups)
        if budget_exceeded:
            reasons.add("chart_budget")
            charts = []
            status = "flagged"
    return {
        "template": template["id"],
        "status": status,
        "audit": {
            "complete": not reasons,
            "items": len(items),
            "reasons": _reasons_list(reasons),
            "units": units_present[:16],
            **({"min_value": min(values), "max_value": max(values)} if values else {}),
        },
        "charts": charts,
    }


def _shots_chart(arguments: Mapping[str, Any], template: Mapping[str, Any]) -> dict[str, Any]:
    shots = arguments.get("shots")
    if not isinstance(shots, dict):
        raise ValueError("shots-chart template requires a shots delivery record")
    requested = shots.get("requested")
    actual = shots.get("actual")
    if (
        not isinstance(requested, int) or isinstance(requested, bool) or requested < 1
        or not isinstance(actual, int) or isinstance(actual, bool) or actual < 0
    ):
        raise ValueError("shots delivery record is invalid")
    reasons: set[str] = set()
    if actual > requested:
        reasons.add("overdelivery")
    elif actual < requested:
        reasons.add("underdelivery")
    # Delivery counts are honest numbers: the requested/actual gap chart is the
    # audit made visible, so this template draws even while flagged.
    return {
        "template": template["id"],
        "status": "flagged" if reasons else "complete",
        "audit": {
            "complete": not reasons,
            "items": 1,
            "reasons": _reasons_list(reasons),
            "units": ["count"],
        },
        "charts": [{
            "kind": "bar",
            "unit": "count",
            "items": [
                {"name": "requested", "value": requested},
                {"name": "actual", "value": actual},
            ],
        }],
    }


def render(arguments: Mapping[str, Any], preset: str | None = None) -> dict[str, Any]:
    """Company-agent local entry for the analysis render tool."""

    del preset  # visibility per preset is governed by contracts/presets.json
    template_id = arguments.get("template")
    if not isinstance(template_id, str) or not template_id or len(template_id) > 128:
        raise ValueError("analysis template id is invalid")
    template = load_templates().get(template_id)
    if template is None:
        raise ValueError("unknown analysis template")
    if template_id == "metric-summary":
        row = _metric_summary(arguments, template)
    elif template_id == "shots-audit":
        row = _shots_audit(arguments, template)
    elif template_id == "metric-quantiles":
        row = _metric_quantiles(arguments, template)
    elif template_id == "shots-chart":
        row = _shots_chart(arguments, template)
    else:  # pragma: no cover - exhaustive contract ids fail closed anyway
        raise ValueError("unknown analysis template")
    try:
        validate_output_content(row, reference=True)
    except ValueError as exc:
        raise ValueError("analysis output violates content rules") from exc
    return row
