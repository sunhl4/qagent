from __future__ import annotations

from typing import Any, Mapping, Protocol

Args = Mapping[str, Any]
Result = Mapping[str, Any]


class CatalogPort(Protocol):
    def list_engines(self, args: Args) -> Result: ...


class PinPort(Protocol):
    def pin_circuit(self, args: Args) -> Result: ...


class HubPort(Protocol):
    def list_assets(self, args: Args) -> Result: ...
    def describe(self, args: Args) -> Result: ...
    def choose(self, args: Args) -> Result: ...
    def validate(self, args: Args) -> Result: ...
    def translate(self, args: Args) -> Result: ...


class WorkflowPort(Protocol):
    def circuit_job(self, args: Args) -> Result: ...


class QDataPort(Protocol):
    def list_providers(self, args: Args) -> Result: ...
    def run_recipe(self, args: Args) -> Result: ...
    def submit_job(self, args: Args) -> Result: ...
    def get_job(self, args: Args) -> Result: ...
    def list_assets(self, args: Args) -> Result: ...
    def get_run_record(self, args: Args) -> Result: ...
    def dequant_gate(self, args: Args) -> Result: ...
    def sandbox_exec(self, args: Args) -> Result: ...


class QChemPort(Protocol):
    def run(self, args: Args) -> Result: ...
    def export_parity(self, args: Args) -> Result: ...


class IonstackPort(Protocol):
    def twin_identity(self, args: Args) -> Result: ...
    def twin_run(self, args: Args) -> Result: ...
    def compile_estimate(self, args: Args) -> Result: ...


class RoutePort(Protocol):
    def compile_estimate(self, args: Args) -> Result: ...


class QiskitPort(Protocol):
    def import_circuit(self, args: Args) -> Result: ...
    def export_circuit(self, args: Args) -> Result: ...
    def transpile(self, args: Args) -> Result: ...
    def aer_run(self, args: Args) -> Result: ...
    def ibm_run(self, args: Args) -> Result: ...


class CirqPort(Protocol):
    def import_circuit(self, args: Args) -> Result: ...
    def export_circuit(self, args: Args) -> Result: ...
    def simulator_run(self, args: Args) -> Result: ...


class PennylanePort(Protocol):
    def import_circuit(self, args: Args) -> Result: ...
    def export_circuit(self, args: Args) -> Result: ...
    def simulator_run(self, args: Args) -> Result: ...


class DocsPort(Protocol):
    def search(self, args: Args) -> Result: ...


class CodexPort(Protocol):
    def oneshot(self, args: Args) -> Result: ...
    def attended(self, args: Args) -> Result: ...
